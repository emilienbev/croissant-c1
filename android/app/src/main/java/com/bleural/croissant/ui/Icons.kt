/** Builds one glyph on the 24-unit grid. Paths are black; [Glyph] tints them. */
internal class Sheet(name: String) {
    private val builder = ImageVector.Builder(
        name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f,
    )

    fun stroke(d: String, width: Float = 2f) {
        builder.addPath(
            addPathNodes(d), stroke = SolidColor(Color.Black), strokeLineWidth = width,
            strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,
        )
    }

    fun fill(d: String, alpha: Float = 1f, evenOdd: Boolean = false) {
        builder.addPath(
            addPathNodes(d), fill = SolidColor(Color.Black), fillAlpha = alpha,
            pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
        )
    }

    fun both(d: String, width: Float = 2f) {
        builder.addPath(
            addPathNodes(d), fill = SolidColor(Color.Black), stroke = SolidColor(Color.Black),
            strokeLineWidth = width, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,
        )
    }

    /** Three 90 degree arcs concentric about the dot at (12, 19.5). */
    fun wifi() {
        stroke("M2.45 9.95A13.5 13.5 0 0 1 21.55 9.95M5.64 13.14A9 9 0 0 1 18.36 13.14M8.82 16.32A4.5 4.5 0 0 1 15.18 16.32")
        fill(circle(12f, 19.5f, 1.6f))
    }

    /** The battery outline and its nub; the fill is the caller's. */
    fun battery() {
        stroke(rect(2f, 7f, 17f, 10f, 2.5f))
        fill(rect(20.5f, 10f, 2f, 4f, 1f))
    }

    /** Three bars, the ones above [lit] at 30%. */
    fun signal(lit: Int) {
        fill(rect(3f, 14f, 4f, 7f, 1.5f), alpha = if (lit >= 1) 1f else 0.3f)
        fill(rect(10f, 9f, 4f, 12f, 1.5f), alpha = if (lit >= 2) 1f else 0.3f)
        fill(rect(17f, 4f, 4f, 17f, 1.5f), alpha = if (lit >= 3) 1f else 0.3f)
    }

    fun build(): ImageVector = builder.build()
}

internal fun glyph(name: String, draw: Sheet.() -> Unit): ImageVector = Sheet(name).apply(draw).build()

/** An SVG `<rect>` with rounded corners as path data. */
private fun rect(x: Float, y: Float, w: Float, h: Float, rx: Float): String {
    val sw = w - 2 * rx
    val sh = h - 2 * rx
    return "M${x + rx} $y h$sw a$rx $rx 0 0 1 $rx $rx v$sh a$rx $rx 0 0 1 ${-rx} $rx " +
        "h${-sw} a$rx $rx 0 0 1 ${-rx} ${-rx} v${-sh} a$rx $rx 0 0 1 $rx ${-rx} z"
}

/** An SVG `<circle>` as path data. */
private fun circle(cx: Float, cy: Float, r: Float): String =
    "M${cx - r} $cy a$r $r 0 1 0 ${2 * r} 0 a$r $r 0 1 0 ${-2 * r} 0 z"
