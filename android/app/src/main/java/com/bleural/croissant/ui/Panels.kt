/**
 * Everything any panel needs, built once in the shell. A panel takes this and nothing
 * else, so adding or reworking one never touches `AppShell`, which is what keeps separate
 * sessions out of each other's files.
 */
class PanelDeps(
    /** Puts the open panel away: the room's, or whatever a design borrowing these panels has. */
    private val closePanel: () -> Unit,
    val nav: NavState,
    val device: DeviceStatus,
    val settings: SettingsInfo,
    val simLabel: String?,
    val voice: VoiceState,
    val level: () -> Float,
    val levels: () -> FloatArray,
    val recorder: RecorderState,
    val elapsed: () -> Long,
    val recordings: List<Recording>,
    val reminders: List<Reminder>,
    val events: List<Event>,
    val timers: List<Timer>,
    val photos: List<File>,
    /** How many pictures the model has made, for the Photos panel's Generated row. */
    val generated: Int,
    val onRecorder: (RecorderAction) -> Unit,
    val onCancelTimer: (String?) -> Unit,
    val onPhoto: (Photo?) -> Unit,
    /** The Photos panel's selection, deleted in one go. */
    val onDeletePhotos: (List<File>) -> Unit,
    /** The device's metronome, which its screens drive, and what it is set to. */
    val metronome: Metronome,
    val metronomeState: MetronomeState,
    /** The Translator's pair, what is kept for it (both ways round, newest first), and the pair turned round. */
    val translatorPair: LanguagePair,
    val translations: List<Translation>,
    val onSwapTranslator: () -> Unit,
    /** The Translator's local mode, the switch (its cue included), and what it can hear. */
    val local: LocalState,
    val onLocal: (Boolean) -> Unit,
    val localHears: (Language) -> Boolean,
    /** Every place's weather, here first, and the pin; Home's is [Forecasts.home]. */
    val forecasts: Forecasts,
    /** Ask's open conversation with the exchange in flight (ui/Conversations.kt). */
    val ask: AskConversation = AskConversation(voice, null, emptyList()),
) {
    /**
     * Every panel's back: one tick up at the top, the chevron, or the edge drag, all
     * close the panel. It sounds like leaving a screen because it is: before the room,
     * these were screens and backed out through `nav::pop`, which plays this.
     */
    fun close() { closePanel(); Wheel.hush(); Cues.play(Sound.ScreenOut) }
}

/**
 * The device, unpacked into what the panels take. This is the seam and the only place it
 * sits for them: no panel knows [Core], and Core knows no panel (UiShell.kt). [closePanel]
 * is whoever is drawing the panels: the room, or a design borrowing them while it is
 * being built.
 */
@Composable
fun panelDeps(core: Core, nav: NavState, closePanel: () -> Unit): PanelDeps {
    val device by core.device.collectAsStateWithLifecycle()
    val voice by core.voice.collectAsStateWithLifecycle()
    val recorder by core.recorder.collectAsStateWithLifecycle()
    // Read where it is drawn, never here: the level changes every audio frame, and only
    // the meter that follows it should recompose with it.
    val level = core.level.collectAsStateWithLifecycle()
    val esim by core.esim.state.collectAsStateWithLifecycle()
    val reminders by core.reminders.items.collectAsStateWithLifecycle()
    val events by core.events.items.collectAsStateWithLifecycle()
    val timers by core.timers.items.collectAsStateWithLifecycle()
    val photos by core.photos.items.collectAsStateWithLifecycle()
    val generated by core.generated.items.collectAsStateWithLifecycle()
    val recordings by core.recordings.items.collectAsStateWithLifecycle()
    val metronome by core.metronome.state.collectAsStateWithLifecycle()
    val translations by core.translations.items.collectAsStateWithLifecycle()
    val pair = core.translatorPair
    val kept = remember(translations, pair) { core.translations.forPair(pair) }
    val local by core.local.collectAsStateWithLifecycle()
    val forecasts by core.weather.forecasts.collectAsStateWithLifecycle()
    val ask = rememberAskConversation(core, voice)
    return PanelDeps(
        closePanel = closePanel, nav = nav, device = device,
        settings = SettingsInfo(
            ssid = device.ssid,
            serverLabel = core.server.label,
            volume = core.volume,
            muted = core.muted,
            brightness = core.brightness,
            batteryTrack = core.batteryTrack,
            batteryEvery = core.batteryEvery,
        ),
        simLabel = esim.card?.summary ?: esim.simName,
        voice = voice, level = { level.value }, levels = core::levels,
        recorder = recorder, elapsed = core::elapsedMs, recordings = recordings,
        reminders = reminders, events = events, timers = timers, photos = photos,
        generated = generated.size,
        onRecorder = { a ->
            when (a) {
                RecorderAction.Record -> core.record()
                RecorderAction.Pause -> core.pauseRecording()
                RecorderAction.Resume -> core.resumeRecording()
                RecorderAction.Stop -> core.stopRecording()
            }
        },
        onCancelTimer = { runCatching { core.timers.cancel(it) } },
        onPhoto = { core.attachPhoto(it?.jpeg, it?.file) },
        onDeletePhotos = { going -> going.forEach { core.photos.delete(it) } },
        metronome = core.metronome,
        metronomeState = metronome,
        translatorPair = pair,
        translations = kept,
        onSwapTranslator = { core.swapTranslator(); Cues.play(Sound.Commit) },
        local = local,
        onLocal = { on -> core.setLocal(on); Cues.play(if (on) Sound.SwitchOn else Sound.SwitchOff) },
        localHears = core::localHears,
        forecasts = forecasts,
        ask = ask,
    )
}
